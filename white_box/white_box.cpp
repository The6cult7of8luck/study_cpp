double quest2(double a, double b, double c) {
    double p = (a + b + c) / 2, max, c1=c, b1=b;

    if (a>=b && a>=c){
        max = a;
    }
    else if (b>=a && b>=c){
        max = b;
        b1 = a;
    }
    else if (c>=a && c>=b){
        max = c;
        c1 = a;
    }
    

    //проверка на возможность
    if (a <= 0 || b <= 0 || c <= 0) {
        cout << "ОШИБКА: сторона не может быть меньше или равна - 0";
        return 0;
    }
    else if (a + b <= c || a + c <= b || b + c <= a) {
        cout << "ОШИБКА: данный треугольник не существует";
        return 0;
    }

    if (max*max >b1*b1+c1*c1) {
        cout << "Этот треугольник: тупоугольный";
    }
    else if (max * max == b1 * b1 + c1 * c1) {
        cout << "Этот треугольник: прямой";
    }
    else {
        cout << "Этот треугольник: остроугольный";
    }
    cout << "\nПлощадь: " << sqrt(p * (p - a) * (p - b) * (p - c));
    return 0;
}


double quest1(double a, double b, double c) {
    double p = (a + b + c) / 2;

    //проверка на возможность
    if (a <= 0 || b <= 0 || c <= 0) {
        cout << "ОШИБКА: сторона не может быть меньше или равна - 0";
        return 0;
    }
    else if (a + b <= c || a + c <= b || b + c <= a) {
        cout << "ОШИБКА: данный треугольник не существует";
        return 0;
    }

    if (a==b && a==c){
        cout << "Этот треугольник: равносторонний";
    }
    else if (a!=b && a!=c && b!=c) {
        cout << "Этот треугольник: разносторонний";
    }
    else{
        cout << "Этот треугольник: равнобедренный";
    }
    cout << "\nПлощадь: "<<sqrt(p*(p-a)*(p-b)*(p-c));
    return 0;
}


